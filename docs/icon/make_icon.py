#!/usr/bin/env python3
"""
Writes the app icon's Android vector drawables, and an SVG preview, from one description.

The icon is the Colorado Mesh mark (mountains under an arc with a node at its top, in the
Colorado Mesh palette) with the arc closed into a map crosshair ring. It contains no ATAK or TAK
artwork. Run it from the repository root after changing the shapes or colours below:

    python3 docs/icon/make_icon.py

Outputs:
    app/src/main/res/drawable/ic_launcher_background.xml
    app/src/main/res/drawable/ic_launcher_foreground.xml
    app/src/main/res/drawable/ic_launcher_monochrome.xml   (Android 13 themed icons)
    app/src/main/res/drawable/ic_notification.xml          (status bar)
    docs/icon/icon.svg                                     (full-colour preview, 108 x 108)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res/drawable"

# Colorado Mesh palette (Colorado-Mesh/branding, colors/colors.css).
NAVY_TOP, NAVY_BOTTOM = "#011033", "#0A4483"  # blue-9, blue-5
RED, YELLOW, LIGHT_YELLOW = "#DD506D", "#F2B138", "#ECC455"  # red-3, yellow-5, yellow-3
BACK_PEAK = "#16538E"  # blue-1
SNOW_TOP, SNOW_BOTTOM = "#FFFFFF", "#7C9CC8"
GREEN_TOP, GREEN_BOTTOM = "#4CB578", "#106641"  # green-3, green-6
OFF_WHITE = "#EDEDED"

# Geometry, in the 108 x 108 adaptive icon grid. Launchers show the middle 72; keep to a
# radius of 33 around the centre (54, 54).
RING_CX, RING_CY, RING_R, RING_W = 54, 56, 25, 2.6
NODE_CX, NODE_CY = 54, 31
TICKS = [(54, 85, 54, 77), (25, 56, 33, 56), (83, 56, 75, 56)]
BACK = [(30, 74), (45, 57), (58, 74)]
MAIN = [(38, 74), (58, 49), (78, 74)]
SNOWCAP = [(58, 49), (53, 55.5), (56, 54.5), (58, 57), (61, 54), (63.5, 55.5)]
HILLS = [(30, 74), (42, 66), (49, 70), (61, 62), (78, 74)]


def n(v):
    return f"{v:g}"


def poly(points):
    return "M" + " L".join(f"{n(x)},{n(y)}" for x, y in points) + " Z"


def circle(cx, cy, r):
    return (f"M{n(cx - r)},{n(cy)} A{n(r)},{n(r)} 0 1,1 {n(cx + r)},{n(cy)} "
            f"A{n(r)},{n(r)} 0 1,1 {n(cx - r)},{n(cy)} Z")


def line(x1, y1, x2, y2):
    return f"M{n(x1)},{n(y1)} L{n(x2)},{n(y2)}"


def argb(hex_rgb, alpha):
    return f"#{alpha:02X}{hex_rgb[1:]}"


# --- Android vector drawables -------------------------------------------------------------

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by docs/icon/make_icon.py; edit that and run it again. -->\n")


def vector(body, size=108, viewport=108, tint=None, aapt=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    tint_attr = f'\n    android:tint="{tint}"' if tint else ""
    return (HEADER + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}"{tint_attr}>\n'
            + body + "</vector>\n")


def vd_linear(attr, x1, y1, x2, y2, stops):
    items = "".join(f'                <item android:offset="{n(o)}" android:color="{c}" />\n' for o, c in stops)
    return (f'        <aapt:attr name="{attr}">\n'
            f'            <gradient android:type="linear" android:startX="{n(x1)}" android:startY="{n(y1)}"'
            f' android:endX="{n(x2)}" android:endY="{n(y2)}">\n{items}'
            "            </gradient>\n        </aapt:attr>\n")


def vd_path(data, fill=None, stroke=None, width=None, gradient=None, cap=None, indent="    "):
    attrs = [f'android:pathData="{data}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
    if width:
        attrs.append(f'android:strokeWidth="{n(width)}"')
    if cap:
        attrs.append(f'android:strokeLineCap="{cap}"')
    sep = "\n" + indent + "    "
    if gradient:
        return f"{indent}<path{sep}{sep.join(attrs)}>\n{gradient}{indent}</path>\n"
    return f"{indent}<path{sep}{sep.join(attrs)} />\n"


def background_vd():
    grad = vd_linear("android:fillColor", 54, 0, 54, 108, [(0, NAVY_TOP), (1, NAVY_BOTTOM)])
    return vector(vd_path("M0,0 H108 V108 H0 Z", gradient=grad), aapt=True)


def foreground_vd():
    clip = f'        <clip-path android:pathData="{circle(RING_CX, RING_CY, RING_R - 1.4)}" />\n'
    snow = vd_linear("android:fillColor", 0, 49, 0, 74, [(0, SNOW_TOP), (1, SNOW_BOTTOM)])
    hills = vd_linear("android:fillColor", 0, 62, 0, 74, [(0, GREEN_TOP), (1, GREEN_BOTTOM)])
    ring = vd_linear("android:strokeColor", RING_CX - RING_R, 0, RING_CX + RING_R, 0,
                     [(0, RED), (0.5, YELLOW), (1, LIGHT_YELLOW)])
    glow = (f'        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="radial" android:centerX="{NODE_CX}" android:centerY="{NODE_CY}"'
            f' android:gradientRadius="7">\n'
            f'                <item android:offset="0" android:color="{argb(YELLOW, 0xCC)}" />\n'
            f'                <item android:offset="1" android:color="{argb(YELLOW, 0x00)}" />\n'
            "            </gradient>\n        </aapt:attr>\n")
    body = "    <group>\n" + clip
    body += vd_path(poly(BACK), fill=BACK_PEAK, indent="        ")
    body += vd_path(poly(MAIN), gradient=snow, indent="        ")
    body += vd_path(poly(SNOWCAP), fill=SNOW_TOP, indent="        ")
    body += vd_path(poly(HILLS), gradient=hills, indent="        ")
    body += "    </group>\n"
    body += vd_path(circle(RING_CX, RING_CY, RING_R), width=RING_W, gradient=ring)
    for t in TICKS:
        body += vd_path(line(*t), stroke=OFF_WHITE, width=1.8, cap="round")
    body += vd_path(circle(NODE_CX, NODE_CY, 7), gradient=glow)
    body += vd_path(circle(NODE_CX, NODE_CY, 3.2), fill=YELLOW, stroke=SNOW_TOP, width=1)
    return vector(body, aapt=True)


def mark_paths(colour, ring_width, tick_width):
    """The mark in one colour: for themed launcher icons and the status bar."""
    body = "    <group>\n"
    body += f'        <clip-path android:pathData="{circle(RING_CX, RING_CY, RING_R - 1.4)}" />\n'
    for shape in (BACK, MAIN, HILLS):
        body += vd_path(poly(shape), fill=colour, indent="        ")
    body += "    </group>\n"
    body += vd_path(circle(RING_CX, RING_CY, RING_R), stroke=colour, width=ring_width)
    for t in TICKS:
        body += vd_path(line(*t), stroke=colour, width=tick_width, cap="round")
    body += vd_path(circle(NODE_CX, NODE_CY, 4.2), fill=colour)
    return body


def monochrome_vd():
    return vector(mark_paths("#FFFFFFFF", RING_W, 1.8))


def notification_vd():
    # Status bar icons are 24 dp and drawn in white by the system. The mark spans about 27 to 85
    # across and 26.8 to 85 down; a viewport of 64 around (54, 56) gives it a little margin.
    body = '    <group android:translateX="-22" android:translateY="-24">\n'
    body += "".join("    " + line_ + "\n" for line_ in mark_paths("#FFFFFFFF", 3.6, 3.2).splitlines())
    body += "    </group>\n"
    return vector(body, size=24, viewport=64)


# --- SVG preview --------------------------------------------------------------------------

def preview_svg():
    def pts(points):
        return " ".join(f"{n(x)},{n(y)}" for x, y in points)
    ticks = "".join(f'<line x1="{n(a)}" y1="{n(b)}" x2="{n(c)}" y2="{n(d)}" stroke="{OFF_WHITE}" '
                    'stroke-width="1.8" stroke-linecap="round"/>' for a, b, c, d in TICKS)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
<!-- Generated by docs/icon/make_icon.py; edit that and run it again. -->
<defs>
<linearGradient id="bg" gradientUnits="userSpaceOnUse" x1="54" y1="0" x2="54" y2="108"><stop offset="0" stop-color="{NAVY_TOP}"/><stop offset="1" stop-color="{NAVY_BOTTOM}"/></linearGradient>
<linearGradient id="ring" gradientUnits="userSpaceOnUse" x1="{RING_CX - RING_R}" y1="0" x2="{RING_CX + RING_R}" y2="0"><stop offset="0" stop-color="{RED}"/><stop offset="0.5" stop-color="{YELLOW}"/><stop offset="1" stop-color="{LIGHT_YELLOW}"/></linearGradient>
<linearGradient id="snow" gradientUnits="userSpaceOnUse" x1="0" y1="49" x2="0" y2="74"><stop offset="0" stop-color="{SNOW_TOP}"/><stop offset="1" stop-color="{SNOW_BOTTOM}"/></linearGradient>
<linearGradient id="hills" gradientUnits="userSpaceOnUse" x1="0" y1="62" x2="0" y2="74"><stop offset="0" stop-color="{GREEN_TOP}"/><stop offset="1" stop-color="{GREEN_BOTTOM}"/></linearGradient>
<radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="{NODE_CX}" cy="{NODE_CY}" r="7"><stop offset="0" stop-color="{YELLOW}" stop-opacity="0.8"/><stop offset="1" stop-color="{YELLOW}" stop-opacity="0"/></radialGradient>
<clipPath id="inside"><circle cx="{RING_CX}" cy="{RING_CY}" r="{n(RING_R - 1.4)}"/></clipPath>
</defs>
<rect width="108" height="108" fill="url(#bg)"/>
<g clip-path="url(#inside)">
<polygon points="{pts(BACK)}" fill="{BACK_PEAK}"/>
<polygon points="{pts(MAIN)}" fill="url(#snow)"/>
<polygon points="{pts(SNOWCAP)}" fill="{SNOW_TOP}"/>
<polygon points="{pts(HILLS)}" fill="url(#hills)"/>
</g>
<circle cx="{RING_CX}" cy="{RING_CY}" r="{RING_R}" fill="none" stroke="url(#ring)" stroke-width="{RING_W}"/>
{ticks}
<circle cx="{NODE_CX}" cy="{NODE_CY}" r="7" fill="url(#glow)"/>
<circle cx="{NODE_CX}" cy="{NODE_CY}" r="3.2" fill="{YELLOW}" stroke="{SNOW_TOP}" stroke-width="1"/>
</svg>
"""


if __name__ == "__main__":
    RES.mkdir(parents=True, exist_ok=True)
    (RES / "ic_launcher_background.xml").write_text(background_vd())
    (RES / "ic_launcher_foreground.xml").write_text(foreground_vd())
    (RES / "ic_launcher_monochrome.xml").write_text(monochrome_vd())
    (RES / "ic_notification.xml").write_text(notification_vd())
    (ROOT / "docs/icon/icon.svg").write_text(preview_svg())
    print("Wrote the icon drawables and docs/icon/icon.svg")
